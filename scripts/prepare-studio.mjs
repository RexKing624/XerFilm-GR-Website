// Build only the browser editor. The website owns its route and shared chrome.
import {spawnSync} from 'node:child_process';
import {cpSync,mkdirSync,rmSync,existsSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const site=fileURLToPath(new URL('../',import.meta.url));
// Only the public browser editor is part of this repository. Author signing
// servers, keys, release ledgers and uploaded local data are never copied.
const repositoryStudio=path.join(site,'studio');
const localStudio=path.resolve(site,'../XerFilm-GR-Studio');
if(existsSync(path.join(localStudio,'src/main.ts'))){
  mkdirSync(repositoryStudio,{recursive:true});
  for(const name of ['src','public','package.json','package-lock.json','index.html','vite.config.ts','tsconfig.json','LICENSE','NOTICE.md'])
    cpSync(path.join(localStudio,name),path.join(repositoryStudio,name),{recursive:true});
}
const studio=existsSync(path.join(repositoryStudio,'src/main.ts'))?repositoryStudio:path.resolve(site,'../XerFilm-GR-Studio');
const result=spawnSync(process.execPath,[path.join(studio,'node_modules/vite/bin/vite.js'),'build','--base','./'],{cwd:studio,stdio:'inherit'});
if(result.status!==0)process.exit(result.status||1);
const destination=path.join(site,'public/community/studio');
if(existsSync(destination)&&!existsSync(path.join(destination,'.generated-studio')))throw Error('Refusing to replace an unmarked Studio directory.');
rmSync(destination,{recursive:true,force:true});mkdirSync(destination,{recursive:true});
cpSync(path.join(studio,'dist/index.html'),path.join(destination,'editor.html'));
for(const name of ['assets','brand'])cpSync(path.join(studio,'dist',name),path.join(destination,name),{recursive:true});
writeFileSync(path.join(destination,'.generated-studio'),'Embedded user editor; shared shell is generated by the website.\n');
const legacy=path.join(site,'public/studio');
if(existsSync(legacy)&&!existsSync(path.join(legacy,'.generated-studio')))throw Error('Unmarked legacy Studio directory.');
rmSync(legacy,{recursive:true,force:true});mkdirSync(legacy,{recursive:true});
writeFileSync(path.join(legacy,'.generated-studio'),'Legacy URL redirect only.\n');
writeFileSync(path.join(legacy,'index.html'),'<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="refresh" content="0;url=/community/studio/"><title>XerFilm Studio</title></head><body><a href="/community/studio/">Studio</a></body></html>');
console.log('Public editor prepared at /community/studio/. Private author files excluded.');
